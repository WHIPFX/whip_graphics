-- Layout
--   stream/            game assets for Legacy (streamed automatically; files named after base-game assets replace them)
--   stream_enhanced/   the same for GTA V Enhanced, which streams it instead of stream/: the models converted gen8 ->
--                      gen9 (CodeWalker), the map data regenerated from Enhanced 1.0.1158. It has no
--                      hei_kt1_rd_critical_0.ymap (Legacy's only). It is hand-made, so it is marked
--                      .enhanced-manual and the pre-commit hook (.githooks/) leaves it alone.
--   data/     data files registered below (timecycle modifiers, ...)
--   client/   client scripts
--
-- LED streetlights (stream/)
--   9 x .yft               prop_streetlight_01/01b/03/03c/03d/04, prop_traffic_01a/01b/01d: stock poles,
--                          flat LED heads (LED texture embedded), lights warm white 255,227,166 at the LED face.
--                          The housing is on the arm bone and only the LED face is on the glass bone, so a shot
--                          lamp loses just its lit face (light off, dead LED board showing), like stock glass.
--                          Housings use their own pole's metal (same texture, scale and finish as the arm),
--                          with baked shading around the fins, photocell and arm joint.
--                          2.0.4: each model's own copy of the LED faces is smaller (lit 128x256, shot 64x128;
--                          they sit 5-8 m up): the 9 models' GPU memory 3.0 -> 0.9 MB, nothing else changed.
--   m25_2_distlodlights_*  distant LOD-light glow for those props, recoloured (m25_2_ is the active set on Enhanced
--                          too). 1.7.0: build 3889's active set is
--                          m25_2_ (mp2025_02), which replaced vw_ (build 3407's): on 3889 the old vw_ copies did
--                          nothing and distant lamps showed Rockstar's orange again. Made for build 3889.
--   *_critical_*.ymap      placements with their own LightEffect light, recoloured and moved to the LED face.
--
-- The look (2.0.0: data/whippy_led_timecycle.xml + client/look_data.lua + client/look_legacy.lua on Legacy;
-- data/whippy_led_look_snapshots.xml + client/look_snap.lua + client/look_enhanced.lua on Enhanced)
--   GTA VI-style grade tuned shot by shot with the look-dev loop: warm shadows and highlights, soft highlight
--   roll-off, humid cream haze by day, rose dusk, neutral nights. Two parts:
--     - whippy_look on the extra slot at full strength, rewritten once a second from game hour and weather: the
--       tuned look in full for clear weathers, partly for overcast/rain/thunder/fog and snow, off for Halloween, plus
--       the sun-shadow box (dir_shadow_cascade0_scale 10, 1.9.0). Absolute values, so it doesn't dip at dusk/dawn.
--     - whippy_day / whippy_night (Whippy's day and night values) on the main slot, cross-faded by strength (night
--       21:00-05:00, day 07:00-19:00), so GTA blends them with its own city or countryside value. They step aside
--       while another script's modifier is on the main slot and come back the frame it's free.
--   2.0.1: 2.0.0 blended the day/night values in from the countryside stock numbers, which in the city dropped the
--   dusk haze to near black at 20:00 (black band under the sunset); back to strength cross-fades. Dusk haze colour
--   darkened so clouds near the sun keep their shape. 2.0.2: 06:00 dawn key (soft peach haze instead of the grey-blue
--   blend from the night look); Halloween nights use whippy_night_plain so the green moon stays. 2.0.3: glow keyed
--   by game hour in clear weather (bloom strong at night, warm around the sun at dawn and dusk, near stock at midday;
--   only visible with Post FX High and above), and slightly bigger, brighter light halos (misc.coronas.*).
--   Tonemapping.bright A 0.20 / W 5.0 via visual settings
--   (restored on stop). /ledambient toggles the whole look. client/look_data.lua and data/whippy_led_timecycle.xml
--   are generated by work/lookdev/build_look.py from the tuned keyframes; don't edit them by hand.
--   1.9.x day/night crossfade (client/timecycle.lua) is in the archive (whip_graphics_v1.9.1).
--   ON ENHANCED (2.1.0: one pack for both games; whip's whip_platform convar says which, as whip_core reads it): the
--   same tuning, baked into 357 snapshot modifiers through the day per weather group (clear, smog, grey, snow,
--   Halloween) and switched on the extra slot by game hour and weather, because the FiveM natives that rewrite a
--   modifier live are unconfirmed on FiveM Enhanced. Each switch moves values by at most 5% of their daily range.
--   Visual settings only if the build has SetVisualSettingFloat. Both timecycle files load on both games (the
--   snapshots are about 380 KB); each look script runs only on its own game. data/whippy_led_look_snapshots.xml and
--   client/look_snap.lua are generated by work/lookdev/build_look_snap.py; whippy_day / whippy_night /
--   whippy_night_plain are only in data/whippy_led_timecycle.xml (the Enhanced build's copies had the same values).
--
